  function translate(key, language = 'vi', values = {}) {
    if (!['vi', 'en'].includes(language)) throw new Error(`Unsupported interface language: ${language}`);
    if (!Object.hasOwn(messages, key)) throw new Error(`Missing translation: ${key}`);
    return messages[key][language === 'en' ? 1 : 0].replace(/\{(\w+)\}/g, (_, name) => {
      if (!Object.hasOwn(values, name)) throw new Error(`Missing translation value: ${key}.${name}`);
      return String(values[name]);
    });
  }
  function resolveLanguage(search, preferred = 'vi') {
    const language = new URLSearchParams(search).get('lang');
    return ['vi', 'en'].includes(language) ? language : ['vi', 'en'].includes(preferred) ? preferred : 'vi';
  }
  function apply(document, language) {
    document.documentElement.lang = language;
    document.title = translate('page.title', language);
    for (const element of document.querySelectorAll('[data-i18n]')) {
      element.textContent = translate(element.getAttribute('data-i18n'), language);
    }
    for (const attribute of ['aria-label', 'title', 'placeholder', 'content', 'copy-message']) {
      for (const element of document.querySelectorAll(`[data-i18n-${attribute}]`)) {
        element.setAttribute(attribute === 'copy-message' ? 'data-copy-message' : attribute, translate(element.getAttribute(`data-i18n-${attribute}`), language));
      }
    }
    const locale = document.querySelector('meta[property="og:locale"]');
    if (locale) locale.content = language === 'en' ? 'en_US' : 'vi_VN';
  }
