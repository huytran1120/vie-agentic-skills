#!/usr/bin/env python3
"""
Import skill from kunchenguid/headless:
Imports 1 genuinely new skill (`headless`) for unattended headless Mac, Linux, and Windows setup over SSH with file-descriptor secret isolation.
"""

import hashlib
import json
import os
import shutil
import stat
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
UPSTREAM_REPO = "kunchenguid/headless"
UPSTREAM_REV = "fe1a381c6f382ec3c9822da0e706484414bc63e0"
AUTHOR = "Kun Chen (kunchenguid)"
AUTHOR_URL = "https://github.com/kunchenguid"

UPSTREAM_DIR = Path("/tmp/headless-repo")
if not UPSTREAM_DIR.exists() or not (UPSTREAM_DIR / "skills/headless/SKILL.md").exists():
    raise RuntimeError(f"Upstream clone not found at {UPSTREAM_DIR}")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def main():
    skill_id = "headless"
    source_dir_rel = "skills/headless"
    source_skill_md = "skills/headless/SKILL.md"
    final_cat = "devops"
    tags = [
        "headless",
        "ssh",
        "macos",
        "linux",
        "windows",
        "nixos",
        "nix-darwin",
        "tailscale",
        "devops",
        "security",
    ]
    description = (
        'Set up a headless Mac (Apple silicon), Linux or Windows machine over SSH, step by step, '
        'from "an admin account with a password and SSH on" to a configured machine with key-only SSH, '
        'automatic sign-in, never-sleep settings and optional Tailscale - on a Mac with Determinate Nix '
        'and nix-darwin, on Linux with a NixOS module (installing NixOS with nixos-anywhere if the user wants) '
        'or a distro-neutral script for Debian, Ubuntu and Fedora, on Windows 11 or Windows Server with a '
        'rerunnable PowerShell configuration - then restart it and confirm it comes back. Use when the user '
        'wants to set up, configure, update or check a headless Mac mini, Linux server, Windows PC or other '
        'machine they reach only over SSH. The admin password stays in the user\'s secret store (Automic Vault, '
        '1Password, Bitwarden, any command, or a private env file); you only ever name the store entry.'
    )

    dest_dir = REPO_ROOT / "skills" / skill_id
    if dest_dir.exists():
        shutil.rmtree(dest_dir)
    dest_dir.mkdir(parents=True, exist_ok=True)

    file_records = []

    # 1. LICENSE
    src_lic = UPSTREAM_DIR / "LICENSE"
    lic_file = dest_dir / "LICENSE"
    shutil.copy2(src_lic, lic_file)
    lic_file.chmod(0o644)
    lic_sha = sha256_file(lic_file)
    file_records.append({
        "skill_id": skill_id,
        "source_path": "LICENSE",
        "path": f"skills/{skill_id}/LICENSE",
        "source_sha256": sha256_file(src_lic),
        "sha256": lic_sha,
        "executable": False,
    })

    # 2. NOTICE.md
    not_content = f"""# Notices

`{skill_id}` is imported from [`{UPSTREAM_REPO}`](https://github.com/{UPSTREAM_REPO}) at revision `{UPSTREAM_REV}` (`{source_skill_md}`) under the MIT License (Copyright (c) 2026 Kun Chen); see `LICENSE`.

## Purpose & Bundled Payload

- Step-by-step setup, configuration, verification, and unattended restart verification of a headless macOS (Apple silicon), Linux (NixOS, Debian, Ubuntu, Fedora), or Windows (Windows 11, Windows Server 2025) machine over SSH.
- Secret isolation via `scripts/secret-run.sh`: the admin password stays in the user's secret store (Automic Vault, 1Password CLI, Bitwarden CLI, a custom command, or a mode-0600 env file) and is piped on file descriptor 3; the agent only ever handles the store entry reference.
- Standalone payload includes `SKILL.md`, `references/` (`mac.md`, `linux.md`, `windows.md`, `secrets.md`, `tailscale.md`), `scripts/` (`secret-run.sh`, `mac/`, `linux/`, `windows/`, `remote/`), `assets/` (`darwin/`, `nixos/`, `windows/`), and bundled copies of the upstream Nix modules in `modules/` (`darwin/headless.nix`, `nixos/headless.nix`).

## Prerequisites & Safe Operation

- Local machine prerequisites: `bash`, `ssh`, `tar` (and `nix` only when using `install-nixos.sh` with `nixos-anywhere`).
- Target machine prerequisites: reachable over SSH with an administrator/sudo account and password stored in the chosen secret store.
- Installation via `./vas install` or the no-clone Web Agent Prompt only links or copies static files and writes `.vas-manifest.json`. No script, SSH connection, secret store command, or Nix build is executed during installation.
"""
    not_file = dest_dir / "NOTICE.md"
    not_file.write_text(not_content.strip() + "\n", encoding="utf-8")
    not_file.chmod(0o644)
    not_sha = sha256_file(not_file)
    file_records.append({
        "skill_id": skill_id,
        "source_path": f"{source_dir_rel}/NOTICE.md (generated by VAS)",
        "path": f"skills/{skill_id}/NOTICE.md",
        "source_sha256": not_sha,
        "sha256": not_sha,
        "executable": False,
    })

    # 3. Copy all files from upstream skills/headless/
    src_skill_dir = UPSTREAM_DIR / "skills/headless"
    for src_path in sorted(src_skill_dir.rglob("*")):
        if src_path.is_dir() or src_path.is_symlink():
            continue
        rel = src_path.relative_to(src_skill_dir)
        dst_path = dest_dir / rel
        dst_path.parent.mkdir(parents=True, exist_ok=True)

        src_mode = os.stat(src_path).st_mode
        is_exec = bool(src_mode & (stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH))
        src_sha = sha256_file(src_path)

        if rel.name == "SKILL.md":
            text = src_path.read_text(encoding="utf-8")
            lines = text.splitlines()
            idx = 1
            while idx < len(lines) and lines[idx].strip() != "---":
                idx += 1
            body = "\n".join(lines[idx + 1:]).lstrip()

            tags_str = json.dumps(tags)
            desc_escaped = json.dumps(description)
            new_frontmatter = f"""---
name: {skill_id}
description: {desc_escaped}
category: {final_cat}
tags: {tags_str}
risk: safe
author: "{AUTHOR}"
author_url: "{AUTHOR_URL}"
source: "https://github.com/{UPSTREAM_REPO}/tree/{UPSTREAM_REV}/{source_dir_rel}"
source_repo: "{UPSTREAM_REPO}"
source_revision: "{UPSTREAM_REV}"
source_path: "{source_skill_md}"
license: "MIT"
license_source: "https://github.com/{UPSTREAM_REPO}/blob/{UPSTREAM_REV}/LICENSE"
compatibility: "Runs on macOS or Linux with bash, ssh and tar (and Nix, only to install NixOS on a Linux machine). The machine being set up is an Apple silicon Mac on a current macOS (tested on macOS 26), or an x86_64 or aarch64 Linux machine with systemd running NixOS, Debian, Ubuntu or Fedora, or a Windows 11 (Home or Pro) or Windows Server 2025 machine, x86_64 or Arm64 (tested on 26H2 and Server 2025)."
metadata:
  short-description: "Headless Mac, Linux or Windows setup over SSH, password never seen"
---

"""
            vas_notes = f"""

---

## VAS installation notes

- Canonical ID: `{skill_id}`
- Source repository: [`{UPSTREAM_REPO}`](https://github.com/{UPSTREAM_REPO}) at commit `{UPSTREAM_REV}` (`{source_skill_md}`).
- Author: {AUTHOR} (`{AUTHOR_URL}`).
- License: MIT (Copyright (c) 2026 Kun Chen); see `LICENSE` and `NOTICE.md`.
- Bundled Nix modules: `modules/darwin/headless.nix` and `modules/nixos/headless.nix` are included inside this skill directory for local inspection and offline reference alongside `assets/`, `references/`, and `scripts/`.
- Install via CLI: `./vas install {skill_id} --target <agent> --mode link` (or `--mode copy`).
"""
            full_content = new_frontmatter + body.rstrip() + vas_notes + "\n"
            dst_path.write_text(full_content, encoding="utf-8")
            dst_path.chmod(0o644)
            is_exec = False
        else:
            shutil.copy2(src_path, dst_path)
            if is_exec:
                dst_path.chmod(0o755)
            else:
                dst_path.chmod(0o644)

        file_records.append({
            "skill_id": skill_id,
            "source_path": f"{source_dir_rel}/{rel}",
            "path": f"skills/{skill_id}/{rel}",
            "source_sha256": src_sha,
            "sha256": sha256_file(dst_path),
            "executable": is_exec,
        })

    # 4. Bundle upstream modules/darwin/headless.nix and modules/nixos/headless.nix
    src_modules_dir = UPSTREAM_DIR / "modules"
    for src_mod in sorted(src_modules_dir.rglob("*.nix")):
        rel_mod = src_mod.relative_to(UPSTREAM_DIR)  # modules/darwin/headless.nix
        dst_mod = dest_dir / rel_mod
        dst_mod.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(src_mod, dst_mod)
        dst_mod.chmod(0o644)
        mod_sha = sha256_file(dst_mod)
        file_records.append({
            "skill_id": skill_id,
            "source_path": str(rel_mod),
            "path": f"skills/{skill_id}/{rel_mod}",
            "source_sha256": sha256_file(src_mod),
            "sha256": mod_sha,
            "executable": False,
        })

    file_records.sort(key=lambda r: r["path"])

    skill_entry = {
        "id": skill_id,
        "canonical_id": skill_id,
        "name": skill_id,
        "path": f"skills/{skill_id}",
        "description": description,
        "category": final_cat,
        "tags": tags,
        "risk": "safe",
        "author": AUTHOR,
        "author_url": AUTHOR_URL,
        "source": f"https://github.com/{UPSTREAM_REPO}/tree/{UPSTREAM_REV}/{source_dir_rel}",
        "source_repo": UPSTREAM_REPO,
        "source_revision": UPSTREAM_REV,
        "source_path": source_skill_md,
        "license": "MIT",
        "license_source": f"https://github.com/{UPSTREAM_REPO}/blob/{UPSTREAM_REV}/LICENSE",
    }

    import_manifest = {
        "source_repo": UPSTREAM_REPO,
        "source_url": f"https://github.com/{UPSTREAM_REPO}",
        "revision": UPSTREAM_REV,
        "author": AUTHOR,
        "author_url": AUTHOR_URL,
        "license": "MIT",
        "license_source": f"https://github.com/{UPSTREAM_REPO}/blob/{UPSTREAM_REV}/LICENSE",
        "skill_count": 1,
        "skipped": [],
        "namespaces": {},
        "duplicate_check": {
            "catalog_count_before": 4073,
            "upstream_is_fork": False,
            "methods": [
                "canonical-id/name",
                "source-repo/path",
                "raw-sha256",
                "normalized-body",
                "renamed-body",
                "body-containment",
                "7-word-shingles",
            ],
            "collision_rationale": "Exact and high-similarity comparison against all 4,073 catalog skills identified zero existing duplicates. `headless` is a genuinely new, self-contained cross-platform SSH headless machine provisioning and verification skill with file-descriptor secret isolation.",
        },
        "adaptations": [
            "Preserve upstream payload structure: SKILL.md, references/, scripts/, and assets/ under Open Agent Skills format.",
            "Bundle upstream Nix modules (modules/darwin/headless.nix and modules/nixos/headless.nix) inside skills/headless/modules/ for complete standalone inspection and reference.",
            "Append reversible VAS installation, attribution, prerequisites, and safety notes to SKILL.md.",
            "Include upstream MIT LICENSE and add NOTICE.md clarifying standalone operation, secret-store piping, and runtime prerequisites.",
            "Preserve executable bits (0755) on all 29 executable shell scripts and non-executable bits (0644) on sourced libraries, PowerShell scripts, Nix files, JSON configs, and documentation.",
            "Map `headless` to the existing `devops` category to preserve the 119-category taxonomy.",
            "No runtime, SSH connection, secret store command, or external service is executed during installation.",
        ],
        "skills": [skill_entry],
        "files": file_records,
    }

    manifest_path = REPO_ROOT / "data" / "headless-import.json"
    manifest_path.write_text(json.dumps(import_manifest, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Wrote {manifest_path} ({len(file_records)} files)")

    # Update data/source-credits.json
    credits_path = REPO_ROOT / "data" / "source-credits.json"
    credits = json.loads(credits_path.read_text(encoding="utf-8"))
    credits["sections"]["headless"] = [
        f"- **[kunchenguid/headless](https://github.com/{UPSTREAM_REPO}/tree/{UPSTREAM_REV})**: Unattended headless macOS, Linux, and Windows setup over SSH by {AUTHOR} at revision `{UPSTREAM_REV}` under the MIT License.",
        "- Configures key-only SSH, automatic sign-in, never-sleep power policies, and optional Tailscale across Apple silicon Macs (Determinate Nix + nix-darwin), Linux (NixOS module, nixos-anywhere, or distro-neutral script for Debian/Ubuntu/Fedora), and Windows 11 / Windows Server 2025 (OpenSSH + PowerShell), then verifies every setting across a reboot.",
        "- Keeps the admin password in the user's secret store (Automic Vault, 1Password, Bitwarden, custom command, or mode-0600 env file) and pipes it on file descriptor 3 via `scripts/secret-run.sh` so the agent only ever handles the store entry name.",
        "- Standalone payload includes `SKILL.md`, `LICENSE`, `NOTICE.md`, `references/`, `scripts/`, `assets/`, and bundled `modules/darwin/headless.nix` and `modules/nixos/headless.nix`.",
        "- Installation via `./vas install` only links or copies static files and writes `.vas-manifest.json`. No script, SSH session, or secret store command is executed during installation.",
    ]
    credits_path.write_text(json.dumps(credits, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Updated {credits_path}")

    # Update data/catalog.json
    cat_path = REPO_ROOT / "data" / "catalog.json"
    cat_data = json.loads(cat_path.read_text(encoding="utf-8"))
    existing_skills = [s for s in cat_data["skills"] if s["id"] != skill_id]
    existing_skills.append(skill_entry)
    existing_skills.sort(key=lambda x: x["id"])
    cat_data["skills"] = existing_skills
    cat_data["total"] = len(existing_skills)
    cat_path.write_text(json.dumps(cat_data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    print(f"Updated {cat_path} with total {len(existing_skills)} skills.")


if __name__ == "__main__":
    main()
