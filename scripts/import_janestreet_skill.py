#!/usr/bin/env python3
"""
Import socratic-tutor from janestreet/agent_skills.
Validates upstream files, copies into skills/socratic-tutor,
adds VAS installation notes, NOTICE.md, LICENSE,
records provenance to data/janestreet-import.json,
and updates data/catalog.json.
"""

import hashlib
import json
import os
import shutil
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
UPSTREAM_REPO = "janestreet/agent_skills"
UPSTREAM_REV = "7c6715c29548a3b39d4a9545c698ee4fd17a7213"
AUTHOR = "Jane Street Group, LLC"
AUTHOR_URL = "https://github.com/janestreet"

UPSTREAM_DIR = Path("/tmp/janestreet-agent-skills")
if not UPSTREAM_DIR.exists() or not (UPSTREAM_DIR / "socratic-tutor/SKILL.md").exists():
    raise RuntimeError(f"Upstream clone not found at {UPSTREAM_DIR}")


def sha256_file(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while chunk := f.read(65536):
            h.update(chunk)
    return h.hexdigest()


def main():
    skill_id = "socratic-tutor"
    target_dir = REPO_ROOT / "skills" / skill_id
    if target_dir.exists():
        shutil.rmtree(target_dir)
    target_dir.mkdir(parents=True, exist_ok=True)

    # 1. Copy upstream license as LICENSE
    license_src = UPSTREAM_DIR / "LICENSE.md"
    license_dst = target_dir / "LICENSE"
    shutil.copy2(license_src, license_dst)

    # 2. Generate NOTICE.md
    notice_text = f"""# Notice for {skill_id}

This skill is adapted from upstream repository [{UPSTREAM_REPO}](https://github.com/{UPSTREAM_REPO})
at commit revision `{UPSTREAM_REV}`.

- Author: {AUTHOR}
- Upstream License: MIT License (see LICENSE)
- Source Path: `socratic-tutor/SKILL.md`
- Adapted for Vie Agentic Skill (VAS) distribution.

## Reversible Adaptations

1. Packaged under the Open Agent Skills specification (`skills/{skill_id}/SKILL.md`).
2. Maintained upstream MIT license in `LICENSE`.
3. Appended standard VAS installation notes and metadata to `SKILL.md`.
4. Standalone operation verified without requiring external network access or NPX runtime dependencies.
"""
    notice_dst = target_dir / "NOTICE.md"
    notice_dst.write_text(notice_text, encoding="utf-8")

    # 3. Process SKILL.md
    raw_skill_md = (UPSTREAM_DIR / "socratic-tutor/SKILL.md").read_text(encoding="utf-8")
    raw_sha = sha256_file(UPSTREAM_DIR / "socratic-tutor/SKILL.md")

    vas_notes = f"""

## VAS installation notes

This skill is curated and verified by **Vie Agentic Skill (VAS)** from [{UPSTREAM_REPO}](https://github.com/{UPSTREAM_REPO}).
- Canonical ID: `{skill_id}`
- Upstream Commit: `{UPSTREAM_REV}`
- License: MIT License (Copyright (c) 2026 Jane Street Group, LLC)
- Category: `education`

### Usage with AI Agents

When installed via `./vas install {skill_id} --target <agent> --mode link`, the skill instructs your coding agent (Codex, Claude Code, Cursor, Antigravity) to act as a rigorous personal tutor using the Socratic method when you say "teach me X", "quiz me on X", or "drill me on X".
"""
    adapted_skill_md = raw_skill_md.rstrip() + vas_notes
    skill_md_dst = target_dir / "SKILL.md"
    skill_md_dst.write_text(adapted_skill_md, encoding="utf-8")

    # Record files
    packaged_files = [
        {
            "skill_id": skill_id,
            "source_path": "LICENSE.md",
            "path": f"skills/{skill_id}/LICENSE",
            "source_sha256": sha256_file(license_src),
            "sha256": sha256_file(license_dst),
            "executable": False,
        },
        {
            "skill_id": skill_id,
            "source_path": f"skills/{skill_id}/NOTICE.md (generated by VAS)",
            "path": f"skills/{skill_id}/NOTICE.md",
            "source_sha256": sha256_file(notice_dst),
            "sha256": sha256_file(notice_dst),
            "executable": False,
        },
        {
            "skill_id": skill_id,
            "source_path": "socratic-tutor/SKILL.md",
            "path": f"skills/{skill_id}/SKILL.md",
            "source_sha256": raw_sha,
            "sha256": sha256_file(skill_md_dst),
            "executable": False,
        },
    ]

    import_manifest = {
        "source_repo": UPSTREAM_REPO,
        "source_url": f"https://github.com/{UPSTREAM_REPO}",
        "revision": UPSTREAM_REV,
        "author": AUTHOR,
        "author_url": AUTHOR_URL,
        "license": "MIT",
        "license_source": f"https://github.com/{UPSTREAM_REPO}/blob/{UPSTREAM_REV}/LICENSE.md",
        "skill_count": 1,
        "skipped": [],
        "namespaces": {},
        "duplicate_check": {
            "catalog_count_before": 4075,
            "upstream_is_fork": False,
            "methods": [
                "canonical-id/name",
                "source-repo/path",
                "raw-sha256",
                "normalized-body",
                "renamed-body",
                "body-containment",
                "7-word-shingles",
            ],
            "collision_rationale": "Exact and shingle similarity comparison against all 4,075 catalog skills identified zero existing duplicates (0.0000 max 7-word shingle Jaccard similarity). `socratic-tutor` is a genuinely new skill from Jane Street establishing an active Socratic teaching protocol with diagnostic placement, levels 0-5 skill mapping, spaced review, and final assessment.",
        },
        "adaptations": [
            "Preserve upstream payload structure: SKILL.md under Open Agent Skills format.",
            "Include upstream MIT LICENSE.md as LICENSE alongside VAS NOTICE.md clarifying standalone operation.",
            "Append reversible VAS installation, attribution, and prerequisites notes to SKILL.md.",
            "Map `socratic-tutor` to the existing `education` category to preserve the 119-category taxonomy.",
            "No script, external network request, or NPX dependency is required.",
        ],
        "skills": [
            {
                "id": skill_id,
                "canonical_id": skill_id,
                "name": skill_id,
                "path": f"skills/{skill_id}",
                "description": "Structured Socratic tutoring when the user explicitly asks to be taught, quizzed, or drilled to mastery on a topic: diagnostic placement, a skill map with levels 0-5, spaced review, and a final assessment. Trigger phrases: 'teach me', 'tutor me', 'quiz me', 'drill me', 'help me master'. Not for one-off 'explain X' or 'what is X' questions.",
                "category": "education",
                "tags": [
                    "socratic-tutor",
                    "tutoring",
                    "socratic-method",
                    "education",
                    "learning",
                    "mastery",
                    "quiz",
                    "drill",
                    "jane-street",
                ],
                "risk": "safe",
                "author": AUTHOR,
                "author_url": AUTHOR_URL,
                "source": f"https://github.com/{UPSTREAM_REPO}/tree/{UPSTREAM_REV}/socratic-tutor",
                "source_repo": UPSTREAM_REPO,
                "source_revision": UPSTREAM_REV,
                "source_path": "socratic-tutor/SKILL.md",
                "license": "MIT",
                "license_source": f"https://github.com/{UPSTREAM_REPO}/blob/{UPSTREAM_REV}/LICENSE.md",
            }
        ],
        "files": packaged_files,
    }

    manifest_path = REPO_ROOT / "data/janestreet-import.json"
    with open(manifest_path, "w", encoding="utf-8") as f:
        json.dump(import_manifest, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"✓ Saved import manifest: {manifest_path}")

    # Update data/catalog.json
    catalog_path = REPO_ROOT / "data/catalog.json"
    with open(catalog_path, "r", encoding="utf-8") as f:
        catalog = json.load(f)

    # Remove if existing, then append
    catalog["skills"] = [s for s in catalog["skills"] if s["id"] != skill_id]
    catalog["skills"].append(import_manifest["skills"][0])
    with open(catalog_path, "w", encoding="utf-8") as f:
        json.dump(catalog, f, indent=2, ensure_ascii=False)
        f.write("\n")
    print(f"✓ Updated {catalog_path} with skill {skill_id}")


if __name__ == "__main__":
    main()
